#!/usr/bin/env bash
# Fetch the third-party apps aosp_pc_x86_64 preinstalls and set each up as a prebuilt
# /product app in aosp/device/android-pc/apps/<Name>/ (the APK + a generated Android.bp);
# aosp-device/pc/pc.mk installs every app found there. Downloads are kept in out/downloads/.
#
#   tools/fetch-apps.sh [chromium] [fdroid] [microg] [termux] [smartdock]   default: all five
#
# - Chromium for Android x86_64: the Chromium project's own "AndroidDesktop_x64"
#   continuous build, open source (Chrome itself has no x86_64 APK outside the Play
#   Store); CHROMIUM_REV picks the revision (default: the one tested in F3a).
# - F-Droid: https://f-droid.org/F-Droid.apk, checked against the signing certificate
#   F-Droid publishes (SHA-256 43:23:8D:51:...:C9:CC:AB).
# - microG GmsCore (as com.google.android.gms): the microG project's GitHub release
#   MICROG_VER, checked against microG's signing certificate (SHA-256
#   9B:D0:67:27:...:D1:41:65). Installed privileged and enabled (aosp-device/microg.mk).
# Google's Play Store and WebView are not built in: Play Store is a user-added extra
# (tools/add-google-extras.sh, docs/google-extras.md) and AOSP's WebView is the provider.
# - Termux (com.termux) with its Termux:API and Termux:Boot add-ons: F-Droid's builds,
#   pinned by version code and SHA-256 and checked against the certificate F-Droid signs
#   Termux with (SHA-256 228F:B2:CF:...:D4:1C:42), so F-Droid updates install over them.
#   Termux's APK keeps its JNI libraries compressed (extractNativeLibs="true"), and a
#   /product app's libraries are not extracted at boot: the x86_64 ones are unpacked to
#   apps/Termux/lib/x86_64/, which pc.mk installs beside the unchanged APK (F9j).
# - Smart Dock (cu.axel.smartdock), a desktop launcher with a dock and freeform windows:
#   F-Droid's build, pinned by version code and SHA-256 and checked against the certificate
#   F-Droid signs it with (SHA-256 51:8E:C9:46:...:7D:C3:E9:6C). The default launcher (H4,
#   aosp-device/desktop/smartdock-setup.sh).
set -euo pipefail
ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
APPS=$ROOT/aosp/device/android-pc/apps
HOST=$ROOT/aosp/out/host/linux-x86/bin


install_app() {   # install_app NAME APK SOURCE-DESCRIPTION [EXTRA-BP-LINES]
    local dst=$APPS/$1
    rm -rf "$dst" && mkdir -p "$dst"
    cp "$2" "$dst/$1.apk"
    cat > "$dst/Android.bp" <<BP
// Generated by tools/fetch-apps.sh: $3.
android_app_import {
    name: "$1",
    apk: "$1.apk",
    // Signed by its publisher with APK signature v2+: install it unchanged.
    preprocessed: true,
    product_specific: true,${4:+
    $4}
    dex_preopt: {
        enabled: false,
    },
}
BP
    echo "$1: $dst/$1.apk ($(du -h "$dst/$1.apk" | cut -f1)), $3"
}

chromium() {
    local rev=${CHROMIUM_REV:-1741609}
    local url=https://storage.googleapis.com/chromium-browser-snapshots/AndroidDesktop_x64/$rev
    local dl=$ROOT/out/downloads/chromium-$rev
    mkdir -p "$dl"
    if [[ ! -f $dl/chrome-android-desktop.zip ]]; then
        curl -sSf -o "$dl/chrome-android-desktop.zip.part" "$url/chrome-android-desktop.zip"
        curl -sSf -o "$dl/REVISIONS" "$url/REVISIONS"
        mv "$dl/chrome-android-desktop.zip.part" "$dl/chrome-android-desktop.zip"
    fi
    unzip -q -o -j -d "$dl" "$dl/chrome-android-desktop.zip" chrome-android-desktop/apks/ChromePublic.apk
    install_app Chromium "$dl/ChromePublic.apk" "Chromium r$rev for Android x86_64 ($url)"
}

fdroid() {
    local dl=$ROOT/out/downloads/fdroid
    local cert=43238d512c1e5eb2d6569f4a3afbf5523418b82e0a3ed1552770abb9a9c9ccab
    mkdir -p "$dl"
    curl -sSfL -o "$dl/F-Droid.apk" https://f-droid.org/F-Droid.apk
    "$HOST/apksigner" verify --print-certs "$dl/F-Droid.apk" 2>/dev/null | grep -q "SHA-256 digest: $cert" ||
        { echo "fetch-apps.sh: F-Droid.apk is not signed with F-Droid's certificate" >&2; exit 1; }
    local ver
    ver=$("$HOST/aapt2" dump badging "$dl/F-Droid.apk" | sed -n "s/.*versionName='\([^']*\)'.*/\1/p")
    install_app F-Droid "$dl/F-Droid.apk" "F-Droid $ver (https://f-droid.org/F-Droid.apk, signature checked)"
}

microg() {
    local ver=${MICROG_VER:-0.3.17.252432}
    local url=https://github.com/microg/GmsCore/releases/download/v$ver
    local dl=$ROOT/out/downloads/microg-$ver
    local cert=9bd06727e62796c0130eb6dab39b73157451582cbd138e86c468acc395d14165
    local name pkg apk
    mkdir -p "$dl"
    rm -rf "$APPS/FakeStore"   # microG's Play Store stub: the real Play Store is an extra
    for name in GmsCore:com.google.android.gms; do
        pkg=${name#*:}; name=${name%%:*}
        # The release names each APK <package>-<versionCode>.apk; skip the -hw (Huawei) ones.
        apk=$(curl -sSfL "https://api.github.com/repos/microg/GmsCore/releases/tags/v$ver" |
              grep -o "\"name\": *\"$pkg-[0-9]*\.apk\"" | cut -d'"' -f4)
        [[ -n $apk ]] || { echo "fetch-apps.sh: no $pkg APK in microG v$ver" >&2; exit 1; }
        [[ -f $dl/$apk ]] || curl -sSfL -o "$dl/$apk" "$url/$apk"
        "$HOST/apksigner" verify --print-certs "$dl/$apk" 2>/dev/null | grep -q "SHA-256 digest: $cert" ||
            { echo "fetch-apps.sh: $apk is not signed with microG's certificate" >&2; exit 1; }
        install_app "$name" "$dl/$apk" "microG $ver $pkg ($url/$apk, signature checked)" \
            "privileged: true,
    skip_preprocessed_apk_checks: true,"   # compressed dex: rejected for priv-apps otherwise
    done
}

termux() {
    local dl=$ROOT/out/downloads/termux
    local cert=228fb2cfe90831c1499ec3ccaf61e96e8e1ce70766b9474672ce427334d41c42
    local spec name apk sha ver
    mkdir -p "$dl"
    # NAME:APK:SHA-256, APK as f-droid.org/repo names it (<package>_<versionCode>.apk).
    for spec in \
        Termux:com.termux_1002.apk:e6265a57eb5ca363808488e3b01955958bed93bc0c8a0d281849b363b11027ec \
        TermuxAPI:com.termux.api_1002.apk:4497dbbf81906df52e59ed387a5223d225aa0de3aca817cc557a621e4dadda44 \
        TermuxBoot:com.termux.boot_1000.apk:6f7cf9b94f539d3efd4af3544ff819947b49395275d8cfa7e5f80de14f3d9cf8; do
        IFS=: read -r name apk sha <<< "$spec"
        if [[ ! -f $dl/$apk ]]; then
            curl -sSfL -o "$dl/$apk.part" "https://f-droid.org/repo/$apk"
            echo "$sha  $dl/$apk.part" | sha256sum -c --quiet
            mv "$dl/$apk.part" "$dl/$apk"
        fi
        echo "$sha  $dl/$apk" | sha256sum -c --quiet
        "$HOST/apksigner" verify --print-certs "$dl/$apk" 2>/dev/null | grep -q "SHA-256 digest: $cert" ||
            { echo "fetch-apps.sh: $apk is not signed with F-Droid's Termux certificate" >&2; exit 1; }
        ver=$("$HOST/aapt2" dump badging "$dl/$apk" | sed -n "s/.*versionName='\([^']*\)'.*/\1/p")
        if [[ $name == Termux ]]; then
            install_app "$name" "$dl/$apk" "$apk ($ver) from https://f-droid.org/repo, signature checked" \
                "skip_preprocessed_apk_checks: true,"   # its JNI libraries are compressed
            unzip -q -o -d "$APPS/$name" "$dl/$apk" 'lib/x86_64/*.so'   # pc.mk installs them
        else
            install_app "$name" "$dl/$apk" "$apk ($ver) from https://f-droid.org/repo, signature checked"
        fi
    done
}

smartdock() {
    local dl=$ROOT/out/downloads/smartdock
    local apk=cu.axel.smartdock_1150.apk ver
    local sha=c7c3231431fac5120012d269cfbdff80a28a38230a6980b0f9b5157a8e8b02ea
    local cert=518ec946cdfd52cd3dc595bca852cc1829066e9c37234665b6dd36e77de3e96c
    mkdir -p "$dl"
    if [[ ! -f $dl/$apk ]]; then
        curl -sSfL -o "$dl/$apk.part" "https://f-droid.org/repo/$apk"
        echo "$sha  $dl/$apk.part" | sha256sum -c --quiet
        mv "$dl/$apk.part" "$dl/$apk"
    fi
    echo "$sha  $dl/$apk" | sha256sum -c --quiet
    "$HOST/apksigner" verify --print-certs "$dl/$apk" 2>/dev/null | grep -q "SHA-256 digest: $cert" ||
        { echo "fetch-apps.sh: $apk is not signed with F-Droid's Smart Dock certificate" >&2; exit 1; }
    ver=$("$HOST/aapt2" dump badging "$dl/$apk" | sed -n "s/.*versionName='\([^']*\)'.*/\1/p")
    install_app SmartDock "$dl/$apk" "$apk ($ver) from https://f-droid.org/repo, signature checked"
}

rm -rf "$ROOT/aosp/device/android-pc/chromium"   # the pre-fetch-apps.sh location
# Play Store and Google WebView, fetched here before they became user-added extras
# (docs/google-extras.md): their modules would install over the extras placeholders.
rm -rf "$APPS/Phonesky" "$APPS/WebViewGoogle"
for app in "${@:-chromium fdroid microg termux smartdock}"; do
    for a in $app; do "$a"; done
done
