#!/usr/bin/env bash
# Fetch Chromium for Android x86_64 (the Chromium project's own "AndroidDesktop_x64"
# continuous build, open source; Chrome itself has no x86_64 APK outside the Play Store)
# and set it up as a prebuilt app of aosp_pc_x86_64 in aosp/device/android-pc/chromium/
# (ChromePublic.apk + a generated Android.bp). aosp-device/pc/pc.mk installs it into
# /product/app when that directory exists.
#
#   tools/fetch-chromium.sh [REVISION]     default: the revision tested in F3a
#
# The zip (~500 MB) is kept in out/downloads/chromium-REVISION/.
set -euo pipefail
ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
rev=${1:-1741609}
url=https://storage.googleapis.com/chromium-browser-snapshots/AndroidDesktop_x64/$rev
dl=$ROOT/out/downloads/chromium-$rev
dst=$ROOT/aosp/device/android-pc/chromium
mkdir -p "$dl"
if [[ ! -f $dl/chrome-android-desktop.zip ]]; then
    curl -sSf -o "$dl/chrome-android-desktop.zip.part" "$url/chrome-android-desktop.zip"
    curl -sSf -o "$dl/REVISIONS" "$url/REVISIONS"
    mv "$dl/chrome-android-desktop.zip.part" "$dl/chrome-android-desktop.zip"
fi
rm -rf "$dst" && mkdir -p "$dst"
unzip -q -j -d "$dst" "$dl/chrome-android-desktop.zip" chrome-android-desktop/apks/ChromePublic.apk
cat > "$dst/Android.bp" <<BP
// Generated by tools/fetch-chromium.sh: Chromium r$rev for Android x86_64
// ($url).
android_app_import {
    name: "Chromium",
    apk: "ChromePublic.apk",
    // Signed by the Chromium builders with APK signature v2: install it unchanged.
    preprocessed: true,
    product_specific: true,
    dex_preopt: {
        enabled: false,
    },
}
BP
echo "Chromium r$rev: $dst/ChromePublic.apk ($(du -h "$dst/ChromePublic.apk" | cut -f1))"
