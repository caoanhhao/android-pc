#!/usr/bin/env bash
# Google Play Store for aosp_gts7l (docs/gts7l.md §22), built into the tablet's /product.
# The PC image leaves it out and mounts a user-added copy at boot (docs/google-extras.md); the
# tablet's images carry its own firmware and stay on this host anyway, so here it is a prebuilt
# like the kernel and Mesa. tools/add-google-extras.sh takes it from Google's arm64 emulator
# image (asks you to accept the Android SDK License Agreement, or --accept-license), and this
# writes out/gts7l-playstore/prebuilt/ of the main checkout: Phonesky.apk, its privapp
# permissions and sysconfig, and an Android.bp. tools/aosp-device-link.sh copies that to
# device/android-pc/gts7l-playstore, which aosp_gts7l.mk picks up.
#
#   tools/gts7l-playstore.sh [--accept-license]
#
# For personal use only: never publish the prebuilt or an image built with it.
set -euo pipefail
WT="$(cd "$(dirname "$0")/.." && pwd)"
ROOT=$WT
[[ -d $ROOT/aosp ]] || ROOT="$(cd "$(git -C "$WT" rev-parse --path-format=absolute --git-common-dir)/.." && pwd)"
OUT=$ROOT/out/gts7l-playstore
extras=$OUT/extras pre=$OUT/prebuilt

"$WT/tools/add-google-extras.sh" --arch arm64 --only playstore "$@" --dir "$extras"
unzip -Z1 "$extras/product/priv-app/Phonesky/Phonesky.apk" | grep '^lib/arm64-v8a/' >/dev/null ||
    { echo "gts7l-playstore: Phonesky.apk has no arm64-v8a libraries" >&2; exit 1; }

rm -rf "$pre" && mkdir -p "$pre"
cp "$extras/product/priv-app/Phonesky/Phonesky.apk" \
   "$extras/product/etc/permissions/privapp-permissions-phonesky.xml" \
   "$extras/product/etc/sysconfig/sysconfig-phonesky.xml" "$extras/VERSION" "$pre/"
cat > "$pre/Android.bp" <<BP
// Generated by tools/gts7l-playstore.sh: Google Play Store from $(cut -d' ' -f1 "$extras/VERSION").
// Proprietary, personal use only. Only aosp_gts7l installs these (aosp_pc_x86_64 filters
// them out, docs/google-extras.md).
android_app_import {
    name: "Phonesky",
    apk: "Phonesky.apk",
    // Signed by Google with APK signature v2+: install it unchanged.
    preprocessed: true,
    product_specific: true,
    privileged: true,
    dex_preopt: {
        enabled: false,
    },
}

prebuilt_etc {
    name: "privapp-permissions-phonesky.xml",
    src: "privapp-permissions-phonesky.xml",
    sub_dir: "permissions",
    product_specific: true,
}

prebuilt_etc {
    name: "sysconfig-phonesky.xml",
    src: "sysconfig-phonesky.xml",
    sub_dir: "sysconfig",
    product_specific: true,
}
BP
echo "gts7l-playstore: $pre ($(du -sh "$pre" | cut -f1)), $(cat "$pre/VERSION")"
